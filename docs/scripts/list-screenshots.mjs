#!/usr/bin/env node
// Lists every ::screenshot placeholder with what it must show, and whether the
// image exists yet. Writes SCREENSHOTS.md and prints a short summary.
// Usage: node scripts/list-screenshots.mjs [en|ru]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs'
import { join, relative, resolve } from 'path'

const locale = process.argv[2] || 'en'
const contentDir = resolve(process.cwd(), 'content', locale)
const publicDir = resolve(process.cwd(), 'public')

const walk = dir =>
  readdirSync(dir, { withFileTypes: true }).flatMap(entry =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)]
  )

const attr = (attrs, name) => (new RegExp(`${name}="([^"]*)"`).exec(attrs) || [])[1] || ''

const rows = []
for (const file of walk(contentDir).filter(f => f.endsWith('.md')).sort()) {
  const text = readFileSync(file, 'utf8')
  for (const m of text.matchAll(/::screenshot\{([^}]*)\}/g)) {
    const src = attr(m[1], 'src')
    const localized = locale === 'en' ? src : src.replace(/^\/screenshots\//, `/screenshots/${locale}/`)
    const done = existsSync(join(publicDir, localized)) || existsSync(join(publicDir, src))
    rows.push({ page: relative(contentDir, file), src: localized, alt: attr(m[1], 'alt'), done })
  }
}

const lines = [
  `# Screenshots (${locale})`,
  '',
  'Generated by `npm run screenshots:list`. Save each image at the path shown, under `public/`.',
  locale === 'en'
    ? 'Russian screenshots go under `public/screenshots/ru/` with the same file names; English ones are used until they exist.'
    : '',
  '',
  `${rows.filter(r => r.done).length} of ${rows.length} done.`,
  '',
  '| Done | Page | File | What to capture |',
  '| --- | --- | --- | --- |',
  ...rows.map(r => `| ${r.done ? '✅' : '⬜'} | ${r.page} | \`public${r.src}\` | ${r.alt.replace(/\|/g, '\\|')} |`),
  '',
]
const output = locale === 'en' ? 'SCREENSHOTS.md' : `SCREENSHOTS.${locale}.md`
writeFileSync(resolve(process.cwd(), output), lines.join('\n'))
console.log(`${rows.filter(r => r.done).length}/${rows.length} screenshots present; list written to ${output}`)
