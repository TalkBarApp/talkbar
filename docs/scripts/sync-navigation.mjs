#!/usr/bin/env node
// Writes the sidebar YAML files for every locale from navigation.config.mjs.
// Usage: node scripts/sync-navigation.mjs [en|ru ...]
import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join, resolve } from 'path'
import matter from 'gray-matter'
import YAML from 'yaml'
import { groups } from '../navigation.config.mjs'

const root = resolve(process.cwd(), 'content')
const locales = process.argv.slice(2).length ? process.argv.slice(2) : ['en', 'ru']

const pagePath = (groupId, page) => (page === 'index' ? `/${groupId}` : `/${groupId}/${page}`)

const buildArea = (locale, areaGroups) => {
  const missing = []
  const body = areaGroups.map(group => {
    const children = group.pages.flatMap(page => {
      const file = join(root, locale, group.id, `${page}.md`)
      if (!existsSync(file)) {
        missing.push(file)
        return []
      }
      const { data } = matter(readFileSync(file, 'utf8'))
      return [
        {
          title: data.navigation?.title || data.title,
          to: pagePath(group.id, page),
          ...(data.navigation?.icon ? { icon: data.navigation.icon } : {}),
        },
      ]
    })
    // `to` is only used by the sidebar to open the group of the current page
    return group.flat ? children : [{ title: group.title[locale] || group.title.en, icon: group.icon, to: `/${group.id}`, children }]
  })
  return { body: body.flat(), missing }
}

for (const locale of locales) {
  if (!existsSync(join(root, locale))) continue
  const outputs = [
    ['navigation-talkbar.yaml', groups.talkbar],
    [join('mcp', 'navigation-mcp.yaml'), groups.mcp],
  ]
  for (const [file, areaGroups] of outputs) {
    const { body, missing } = buildArea(locale, areaGroups)
    const header = '# Generated by `npm run nav:sync` from navigation.config.mjs. Do not edit by hand.\n'
    writeFileSync(join(root, locale, file), header + YAML.stringify({ navigation: false, body }))
    console.log(`✔ ${locale}/${file}`)
    for (const path of missing) console.warn(`  ⚠ missing page: ${path}`)
  }
}
